const missionEntries = MISSION_OPTIONS.flatMap((item) => [
  [item.action_id, item],
  [item.mission_id, item],
  ...item.legacy_action_ids.map((legacyId) => [legacyId, item]),
])

export const MISSION_BY_ACTION = Object.freeze(Object.fromEntries(missionEntries))

export function getMission(missionId) {
  return MISSION_BY_ACTION[missionId] || null
}

export function createMissionState(mission) {
  return {
    mission_id: mission.mission_id,
    action_id: mission.action_id,
    label: mission.label,
    label_en: mission.label_en,
    anomaly_type: mission.anomaly_type,
    mission_effect: mission.mission_effect,
    mission_effect_en: mission.mission_effect_en,
    orbit_profile: {
      ...mission.orbit_profile,
      event_weight_bias: { ...mission.orbit_profile.event_weight_bias },
    },
  }
}
