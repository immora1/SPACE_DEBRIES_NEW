import { readFile, writeFile } from 'node:fs/promises'
import Ajv from 'ajv'
import standaloneCode from 'ajv/dist/standalone/index.js'

const source = await readFile(new URL('../docs/SPACE_DEBRIS_Story_Prompts_and_Schemas.md', import.meta.url), 'utf8')
const specs = {}
const ajv = new Ajv({ allErrors: true, strict: true, code: { source: true } })
for (const task of ['STORY_OUTLINE', 'STORY_OPENING', 'STORY_CONTINUE', 'STORY_ENDING', 'KNOWLEDGE_REVEAL']) {
  const section = source.split(new RegExp(`^# \\d+\\. ${task}\\r?$`, 'm'))[1]?.split(/^# \d+\. /m)[0]
  const prompt = section?.match(/```text\r?\n([\s\S]*?)\r?\n```/)
  const schema = section?.match(/```json\r?\n([\s\S]*?)\r?\n```/)
  if (!prompt || !schema) throw new Error(`Missing prompt/schema for ${task}`)
  specs[task] = { promptTemplate: prompt[1].replace(/\r\n/g, '\n'), schemaEnvelope: JSON.parse(schema[1]) }
  ajv.addSchema(specs[task].schemaEnvelope.schema, task)
}
await writeFile(new URL('../functions/_story/current-spec.generated.js', import.meta.url),
  `// Generated from docs/SPACE_DEBRIS_Story_Prompts_and_Schemas.md. Do not edit.\nexport default ${JSON.stringify(specs, null, 2)}\n`)
await writeFile(new URL('../functions/_story/current-validators.generated.cjs', import.meta.url),
  '// Generated by npm run story:sync-spec. Do not edit.\n' + standaloneCode(ajv, Object.fromEntries(Object.keys(specs).map(key => [key, key]))))
console.log('Synced current five-node story prompts and schemas without content patches.')
